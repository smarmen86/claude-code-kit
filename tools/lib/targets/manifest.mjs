// manifest.mjs — emit a machine-readable manifest.json and a human-readable CATALOG.md.
// These are the single source of truth for counts (README etc. should cite these).

import { join } from "node:path";
import { write } from "../util.mjs";

export function buildManifest(model, repoRoot) {
  const manifest = {
    name: "claude-code-kit",
    generated: new Date().toISOString().slice(0, 10),
    counts: model.counts,
    categories: model.categories.map((c) => ({
      name: c.name,
      count: c.agents.length,
    })),
    agents: model.agents.map((a) => ({
      slug: a.slug,
      name: a.name,
      category: a.category,
      model: a.model || null,
      description: a.description,
    })),
    skills: model.skills,
  };
  write(join(repoRoot, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

  const catBlocks = model.categories
    .map((c) => {
      const rows = c.agents
        .map((a) => `| ${a.emoji || ""} **${a.name}** | \`${a.slug}\` | ${a.description} |`)
        .join("\n");
      return `### ${c.name} (${c.agents.length})\n\n| | Agent | What it does |\n|---|---|---|\n${rows}\n`;
    })
    .join("\n");

  const toc = model.categories
    .map((c) => `- [${c.name}](#${c.name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")}-${c.agents.length}) (${c.agents.length})`)
    .join("\n");

  const catalog = `<!-- Generated by tools/build.mjs — do not edit by hand. -->
# KIT Agent Catalog

**${model.counts.agents} agents** · **${model.counts.skills} skills** · ${model.counts.categories} categories
_Generated ${manifest.generated}_

${toc}

${catBlocks}`;
  write(join(repoRoot, "CATALOG.md"), catalog);

  return manifest;
}
