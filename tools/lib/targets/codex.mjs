// codex.mjs — emit an OpenAI Codex CLI build from the shared agent model.
//
// Mapping (verified against Codex docs, 2026):
//   agents/*.md         -> dist/codex/agents/<slug>.toml   (native subagents, GA Mar 2026)
//   CLAUDE.md           -> dist/codex/AGENTS.md            (persistent instructions)
//   settings.json MCP   -> dist/codex/config.toml          ([mcp_servers.*], snake_case!)
//   skills/             -> copied from repo root by the installer (same SKILL.md spec)
//
// Claude model tier -> Codex reasoning effort (we do NOT hardcode a Codex model id,
// so each subagent inherits the user's configured model):
//   opus -> high, sonnet -> medium, (unset) -> omit.

import { join } from "node:path";
import { write } from "../util.mjs";

function reasoningEffort(model) {
  const m = (model || "").toLowerCase();
  if (m.includes("opus")) return "high";
  if (m.includes("sonnet")) return "medium";
  if (m.includes("haiku")) return "low";
  return "";
}

/** Escape a string for a TOML basic multi-line ("""...""") value. */
function tomlMultiline(text) {
  let s = (text || "")
    .replace(/\\/g, "\\\\")   // escape backslashes first
    .replace(/"""/g, '""\\"'); // defuse any triple-quote runs
  // A multi-line basic string trims one leading newline, so lead with one; and
  // guard a trailing double-quote from fusing with the closing delimiter.
  if (s.endsWith('"')) s += "\n";
  return `"""\n${s}\n"""`;
}

/** Escape a single-line TOML basic string value. */
function tomlString(text) {
  return `"${(text || "").replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

// TOML table names must be bare keys [A-Za-z0-9_-]; slugs already qualify.
function agentToml(a) {
  const effort = reasoningEffort(a.model);
  const lines = [
    "# Generated by tools/build.mjs — edit agents/<slug>.md and rebuild, not this file.",
    `name = ${tomlString(a.slug.replace(/-/g, "_"))}`,
    `description = ${tomlString(a.description || a.name)}`,
  ];
  if (effort) lines.push(`model_reasoning_effort = ${tomlString(effort)}`);
  lines.push("");
  const header = `You are **${a.name}**.${a.vibe ? ` ${a.vibe}` : ""}\n\n`;
  lines.push(`developer_instructions = ${tomlMultiline(header + a.body)}`);
  return lines.join("\n") + "\n";
}

function agentsMd(model) {
  const { counts } = model;
  const cats = model.categories
    .map((c) => `- **${c.name}** (${c.agents.length})`)
    .join("\n");
  return `# Agent Coordinator (Codex CLI)

${counts.agents} specialist subagents in \`~/.codex/agents/\` and ${counts.skills} skills in \`~/.codex/skills/\`.
Delegate to a subagent when a specialist fits the task — don't do it yourself.

## Routing Rules

1. Single-domain task → spawn the matching subagent.
2. Multi-domain task → spawn \`agents_orchestrator\`, or fan out several subagents in parallel.
3. Code → an \`engineering_*\` subagent; review with \`engineering_code_reviewer\` then \`code_simplifier\`.
4. Independent subtasks → run subagents in parallel.
5. Unsure which specialist → \`agents_orchestrator\`.

Invoke a subagent by name (underscored), e.g. "spawn \`engineering_backend_architect\` to design the API".

## Categories

${cats}

## Skills

Reusable workflows live in \`~/.codex/skills/<name>/SKILL.md\` (same spec as Anthropic/Claude skills).
List them with the skills menu; invoke by name. Notable: browse, review, qa, ship, cso, seo, blog, make-pdf.

## Notes

- This file is the Codex equivalent of Claude Code's \`CLAUDE.md\`. Keep it lean; it is injected every turn.
- Generated by \`tools/build.mjs\`. Re-run the build after changing \`agents/\` or \`CLAUDE.md\`.
`;
}

function configToml() {
  return `# Codex CLI config — Klugman IT KIT
# Copy to ~/.codex/config.toml (or merge into your existing one).
# NOTE: MCP servers use snake_case [mcp_servers.*] in Codex (not Claude's camelCase).

approval_policy = "on-request"
sandbox_mode = "workspace-write"
model_reasoning_effort = "medium"

[mcp_servers.playwright]
command = "npx"
args = ["@playwright/mcp@latest"]
startup_timeout_sec = 20
`;
}

function installSh(counts) {
  return `#!/usr/bin/env bash
# Codex CLI installer — Klugman IT KIT
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "\${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
TARGET="\${CODEX_HOME:-$HOME/.codex}"

echo "Installing KIT for Codex CLI -> $TARGET"
mkdir -p "$TARGET/agents" "$TARGET/skills"

echo "[1/4] ${counts.agents} subagents..."
cp -r "$SCRIPT_DIR/agents/"*.toml "$TARGET/agents/"

echo "[2/4] ${counts.skills} skills (from repo root)..."
cp -r "$REPO_ROOT/skills/"* "$TARGET/skills/" 2>/dev/null || echo "      (no skills/ found at repo root — skipped)"

echo "[3/4] AGENTS.md..."
if [ -f "$TARGET/AGENTS.md" ]; then
  echo "      exists — writing AGENTS.override.md instead (wins over AGENTS.md)."
  cp "$SCRIPT_DIR/AGENTS.md" "$TARGET/AGENTS.override.md"
else
  cp "$SCRIPT_DIR/AGENTS.md" "$TARGET/AGENTS.md"
fi

echo "[4/4] config.toml..."
if [ -f "$TARGET/config.toml" ]; then
  echo "      exists — leaving it. Merge $SCRIPT_DIR/config.toml by hand."
else
  cp "$SCRIPT_DIR/config.toml" "$TARGET/config.toml"
fi

echo "Done. Start 'codex' and ask it to spawn a specialist subagent."
`;
}

function installPs1(counts) {
  // ASCII-only: Windows PowerShell reads a no-BOM UTF-8 .ps1 as ANSI and mangles
  // non-ASCII characters (e.g. an em-dash), which breaks script parsing.
  return `# Codex CLI installer (Windows) - Klugman IT KIT
$ErrorActionPreference = "Stop"
$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$RepoRoot  = Resolve-Path (Join-Path $ScriptDir "..\\..")
$Target = if ($env:CODEX_HOME) { $env:CODEX_HOME } else { Join-Path $env:USERPROFILE ".codex" }

Write-Host "Installing KIT for Codex CLI -> $Target" -ForegroundColor Cyan
New-Item -ItemType Directory -Force -Path (Join-Path $Target "agents"), (Join-Path $Target "skills") | Out-Null

Write-Host "[1/4] ${counts.agents} subagents..." -ForegroundColor Yellow
Copy-Item (Join-Path $ScriptDir "agents\\*.toml") (Join-Path $Target "agents") -Force

Write-Host "[2/4] ${counts.skills} skills..." -ForegroundColor Yellow
$Skills = Join-Path $RepoRoot "skills"
if (Test-Path $Skills) { Copy-Item (Join-Path $Skills "*") (Join-Path $Target "skills") -Recurse -Force }

Write-Host "[3/4] AGENTS.md..." -ForegroundColor Yellow
$AgentsMd = Join-Path $Target "AGENTS.md"
if (Test-Path $AgentsMd) { Copy-Item (Join-Path $ScriptDir "AGENTS.md") (Join-Path $Target "AGENTS.override.md") -Force }
else { Copy-Item (Join-Path $ScriptDir "AGENTS.md") $AgentsMd -Force }

Write-Host "[4/4] config.toml..." -ForegroundColor Yellow
$Cfg = Join-Path $Target "config.toml"
if (-not (Test-Path $Cfg)) { Copy-Item (Join-Path $ScriptDir "config.toml") $Cfg -Force }
else { Write-Host "      exists - merge config.toml by hand." -ForegroundColor Gray }

Write-Host "Done." -ForegroundColor Cyan
`;
}

function readme(model) {
  const { counts } = model;
  return `# KIT for Codex CLI

A faithful port of the Klugman IT Claude Code KIT to [OpenAI Codex CLI](https://developers.openai.com/codex).

| Claude Code | Codex CLI |
|---|---|
| \`agents/*.md\` subagents | \`agents/*.toml\` native subagents |
| \`CLAUDE.md\` | \`AGENTS.md\` |
| \`settings.json\` (JSON) | \`config.toml\` (TOML) |
| \`mcpServers\` (camelCase) | \`[mcp_servers.*]\` (snake_case) |
| skills (\`SKILL.md\`) | skills (same spec, copied 1:1) |

**Contents:** ${counts.agents} subagents · ${counts.skills} skills · router \`AGENTS.md\` · \`config.toml\`

## Install

\`\`\`bash
# macOS / Linux / Git Bash
bash dist/codex/install.sh
\`\`\`
\`\`\`powershell
# Windows
powershell -ExecutionPolicy Bypass -File dist\\codex\\install.ps1
\`\`\`

Installs to \`~/.codex/\` (or \`$CODEX_HOME\`). If you already have an \`AGENTS.md\`, the installer
writes \`AGENTS.override.md\` (which wins) instead of clobbering yours.

## Use

Start \`codex\`, then ask it to delegate, e.g.:

> Spawn \`engineering_backend_architect\` to design the payments API, then have \`engineering_code_reviewer\` review it.

Subagent names are the agent slugs with underscores. Each lives in \`~/.codex/agents/<name>.toml\`.

## Regenerating

These files are generated. Edit \`agents/<slug>.md\` (or \`CLAUDE.md\`) at the repo root and run:

\`\`\`bash
node tools/build.mjs codex
\`\`\`

_Opus-tier agents map to \`model_reasoning_effort = "high"\`, Sonnet-tier to \`"medium"\`._
`;
}

export function buildCodex(model, outDir) {
  const files = [];
  for (const a of model.agents) {
    files.push(write(join(outDir, "agents", `${a.slug}.toml`), agentToml(a)));
  }
  write(join(outDir, "AGENTS.md"), agentsMd(model));
  write(join(outDir, "config.toml"), configToml());
  write(join(outDir, "install.sh"), installSh(model.counts));
  const ps1 = installPs1(model.counts);
  const nonAscii = ps1.match(/[^\x00-\x7F]/);
  if (nonAscii) {
    throw new Error(
      `install.ps1 contains non-ASCII char U+${nonAscii[0].codePointAt(0).toString(16)} ` +
      `— Windows PowerShell mangles no-BOM UTF-8. Keep the PowerShell installer ASCII-only.`
    );
  }
  write(join(outDir, "install.ps1"), ps1);
  write(join(outDir, "README.md"), readme(model));
  return { agentFiles: files.length };
}
